import fs from 'node:fs';
import { chromium, open } from './browser';
import { RICH, THINGS, UPS, arena, fight, until } from './drive';
const browser = await chromium.launch();
const { page } = await open(browser, { viewport: { width: 907, height: 510 }, deviceScaleFactor: 1 });
page.on('pageerror', (e) => console.log('ERR', String(e.stack ?? e.message).split('\n').slice(0, 4).join(' | ')));
page.on('console', (m) => { if (m.type() !== 'log' && !m.text().includes('403')) console.log('CON', m.type(), m.text().slice(0, 300)); });
await page.clock.install();
await page.goto('http://127.0.0.1:5176/');
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.clock.pauseAt(Date.now() + 1000);
await until(page, 'Hud');
await arena(page, { hero: 'paladin', wave: 20, weapons: RICH, items: THINGS, ups: UPS, level: 10, gold: 120 });
await until(page, 'Hud');
await fight(page, 600);
const info = await page.evaluate(async () => {
  const g = (window as any).game;
  const a = g.scene.getScene('Arena');
  const l = a.light;
  const drawn = l.drawn.length;
  const first = l.drawn.slice(0, 5).map((i: any) => ({ x: i.x, y: i.y, sx: i.scaleX, a: i.alpha, v: i.visible, f: i.frame.name, cf: i.cameraFilter, tint: i.tintTopLeft }));
  const cam = a.cameras.main;
  const ec = l.emit.camera;
  const shot: string = await new Promise((res) => l.emit.snapshot((img: HTMLImageElement) => res(img.src)));
  return { drawn, first, cam: [cam.scrollX, cam.scrollY, cam.zoom, cam.width, cam.height, cam.id], ec: [ec.scrollX, ec.scrollY, ec.zoom, ec.width, ec.height], crisp: l.crispCam.id, shot, shots: a.world.shots.length };
});
fs.writeFileSync('/tmp/claude-0/-home-user/d341175b-724d-5b7d-ae41-c3200b22a72c/scratchpad/emit.png', Buffer.from(info.shot.split(',')[1], 'base64'));
console.log(JSON.stringify({ ...info, shot: info.shot.length }, null, 1));
const more = await page.evaluate(() => {
  const g = (window as any).game;
  const l = g.scene.getScene('Arena').light;
  const f = l.filter;
  const node = g.renderer.renderNodes.getNode('HoldoutStage');
  const prog = node.light.programManager;
  const suite = prog.getCurrentProgramSuite();
  const u: any = {};
  (suite.program.glUniforms.entries ? Object.entries(suite.program.glUniforms.entries) : []).forEach(([k, v]: [string, any]) => { u[k] = [v.type, v.size, Array.isArray(v.value) || v.value?.length ? Array.from(v.value).slice(0, 4) : v.value]; });
  return { emit: !!f.emit, amount: f.emitAmount, full: f.full, tex: f.emit && [f.emit.width, f.emit.height], u };
});
console.log(JSON.stringify(more));
await page.screenshot({ path: '/tmp/claude-0/-home-user/d341175b-724d-5b7d-ae41-c3200b22a72c/scratchpad/dbg.png' });
await browser.close();
